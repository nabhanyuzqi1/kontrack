// src/utils/transactionMeta.js
var INCOME_CATEGORIES = ["Proyek", "Pembayaran Invoice", "Lainnya"];
var EXPENSE_CATEGORIES = [
  "Operasional",
  "Material",
  "Upah Karyawan/Tukang",
  "Pajak",
  "Pengeluaran Lain"
];
var AUTO_CATEGORY = {
  // Uang masuk dari klien: netto yang benar-benar diterima.
  payment: "Pembayaran Invoice",
  // PPN yang dipungut lalu disetor: beban pajak, bukan "pengeluaran lain".
  tax: "Pajak",
  // Dua kategori pengeluaran yang paling sering salah dibaca AI dari bukti
  // transfer (bon/gendro upah dan pembelian material di toko).
  wage: "Upah Karyawan/Tukang",
  material: "Material"
};
var TX_SOURCE = {
  invoicePayment: "invoice",
  invoicePpn: "invoice-ppn",
  invoiceTaxPayment: "invoice-tax",
  manual: "manual"
};
var INCOME_ALIASES = {
  pembayaran: "Pembayaran Invoice",
  "pembayaran invoice": "Pembayaran Invoice",
  proyek: "Proyek",
  lainnya: "Lainnya",
  lain: "Lainnya"
};
var EXPENSE_ALIASES = {
  // PPN/PPh dari invoice dulu tercatat "Pengeluaran Lain" atau "Pajak".
  pajak: "Pajak",
  "pengeluaran lain": "Pengeluaran Lain",
  operasional: "Operasional",
  material: "Material",
  "upah karyawan/tukang": "Upah Karyawan/Tukang",
  transportasi: "Operasional"
};
var tidy = (s) => String(s ?? "").trim().replace(/\s+/g, " ");
var canonicalCategory = (tx = {}) => {
  const type = tx.type === "expense" ? "expense" : "income";
  const source = String(tx.source || "");
  const auto = source.startsWith("invoice") || tx.isAutoGenerated === true;
  if (auto) {
    if (source === TX_SOURCE.invoicePayment) return AUTO_CATEGORY.payment;
    if (source === TX_SOURCE.invoicePpn || source === TX_SOURCE.invoiceTaxPayment) return AUTO_CATEGORY.tax;
    if (type === "income") return AUTO_CATEGORY.payment;
    if (!source && tx.invoiceId) return AUTO_CATEGORY.tax;
  }
  const raw = tidy(tx.category);
  if (!raw) return type === "expense" ? "Pengeluaran Lain" : "Lainnya";
  const table = type === "expense" ? EXPENSE_ALIASES : INCOME_ALIASES;
  return table[raw.toLowerCase()] || raw;
};
var categoriesFor = (type) => type === "expense" ? EXPENSE_CATEGORIES : INCOME_CATEGORIES;
var WAGE_KEYWORDS = [
  "bon",
  "gendro",
  "kendro",
  "upah",
  "honor",
  "ongkos",
  "opah",
  "tukang",
  "mandor",
  "kuli",
  "pekerja",
  "borongan",
  "harian",
  "lembur",
  "gaji",
  "thr",
  "kerja bakti"
];
var MATERIAL_KEYWORDS = [
  "semen",
  "pasir",
  "split",
  "batu",
  "besi",
  "beton",
  "baja",
  "kayu",
  "papan",
  "triplek",
  "cat",
  "pipa",
  "keramik",
  "genteng",
  "paku",
  "kawat",
  "material",
  "toko bangunan"
];
var hasKeyword = (text, list) => {
  const t = String(text || "").toLowerCase();
  return list.some((k) => new RegExp(`(^|[^a-z])${k}([^a-z]|$)`).test(t));
};
var correctCategoryFromText = (tx = {}) => {
  if (!tx || tx.type !== "expense") return null;
  if (!EXPENSE_CATEGORIES.includes(tx.category)) return null;
  const text = `${tx.description || ""} ${tx.vendor || ""}`;
  if (hasKeyword(text, WAGE_KEYWORDS)) {
    return tx.category === AUTO_CATEGORY.wage ? null : AUTO_CATEGORY.wage;
  }
  if (hasKeyword(text, MATERIAL_KEYWORDS)) {
    return tx.category === AUTO_CATEGORY.material ? null : AUTO_CATEGORY.material;
  }
  return null;
};
export {
  AUTO_CATEGORY,
  EXPENSE_CATEGORIES,
  INCOME_CATEGORIES,
  TX_SOURCE,
  canonicalCategory,
  categoriesFor,
  correctCategoryFromText
};
