// scripts/normalize-transaction-categories.mjs
//
// Menyeragamkan kategori + `source` transaksi lama di koleksi `transactions`
// sehingga sama dengan yang ditulis kode sekarang (utils/transactionMeta.js).
//
// Kenapa perlu: koleksi produksi berisi tiga angkatan penamaan untuk hal yang
// sama. Contoh nyata (261 transaksi, audit 2026-11-15):
//   "Pembayaran"        (kode markInvoicePaid lama)
//   "Pembayaran Invoice" (jalur live)
//   "Pengeluaran Lain"  untuk PPN invoice (kode lama)
//   "Pajak"             untuk PPN invoice (jalur live)
//
// Sifat migrasi: ADITIF dan IDEMPOTEN.
// - Hanya menulis `category` (dan `source` bila kosong) pada dokumen yang
//   nilainya berbeda. Dokumen yang sudah benar tidak disentuh.
// - Tidak menghapus field, tidak mengubah nominal/tanggal/relasi.
// - Precondition `updateTime` supaya dokumen yang berubah di tengah proses
//   tidak tertimpa.
//
// Pemakaian:
//   node scripts/normalize-transaction-categories.mjs           # dry-run
//   node scripts/normalize-transaction-categories.mjs --apply   # tulis

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';

const PROJECT = 'sistem-keuangan-ptpeb';
const DATABASE = 'kontrack';
const BASE = `https://firestore.googleapis.com/v1/projects/${PROJECT}/databases/${DATABASE}/documents`;
const APPLY = process.argv.includes('--apply');

// --- kategori kanonik (cermin utils/transactionMeta.js) --------------------
const AUTO_CATEGORY = { payment: 'Pembayaran Invoice', tax: 'Pajak' };
const TX_SOURCE = {
  invoicePayment: 'invoice',
  invoicePpn: 'invoice-ppn',
  invoiceTaxPayment: 'invoice-tax'
};

const INCOME_ALIASES = {
  pembayaran: 'Pembayaran Invoice',
  'pembayaran invoice': 'Pembayaran Invoice',
  proyek: 'Proyek',
  lainnya: 'Lainnya',
  lain: 'Lainnya'
};
const EXPENSE_ALIASES = {
  pajak: 'Pajak',
  'pengeluaran lain': 'Pengeluaran Lain',
  operasional: 'Operasional',
  material: 'Material',
  'upah karyawan/tukang': 'Upah Karyawan/Tukang',
  transportasi: 'Operasional'
};

const tidy = (s) => String(s ?? '').trim().replace(/\s+/g, ' ');

const canonicalCategory = (tx = {}) => {
  const type = tx.type === 'expense' ? 'expense' : 'income';
  const source = String(tx.source || '');
  const auto = source.startsWith('invoice') || tx.isAutoGenerated === true;

  if (auto) {
    if (source === TX_SOURCE.invoicePayment) return AUTO_CATEGORY.payment;
    if (source === TX_SOURCE.invoicePpn || source === TX_SOURCE.invoiceTaxPayment) return AUTO_CATEGORY.tax;
    if (type === 'income') return AUTO_CATEGORY.payment;
    if (!source && tx.invoiceId) return AUTO_CATEGORY.tax;
  }

  const raw = tidy(tx.category);
  if (!raw) return type === 'expense' ? 'Pengeluaran Lain' : 'Lainnya';
  const table = type === 'expense' ? EXPENSE_ALIASES : INCOME_ALIASES;
  return table[raw.toLowerCase()] || raw;
};

// Sumber kanonik untuk transaksi otomatis yang belum punya `source`.
const canonicalSource = (tx) => {
  if (tx.source) return tx.source;
  if (tx.isAutoGenerated !== true) return null;
  if (tx.type === 'income' && tx.invoiceId) return TX_SOURCE.invoicePayment;
  if (tx.type === 'expense' && tx.invoiceId) return TX_SOURCE.invoicePpn;
  return null;
};

// --- token akses firebase-tools (tidak dicetak) ---------------------------
const tokenPath = path.join(os.homedir(), '.config', 'configstore', 'firebase-tools.json');
const accessToken = JSON.parse(fs.readFileSync(tokenPath, 'utf8'))?.tokens?.access_token;
if (!accessToken) {
  console.error('Token firebase-tools tidak ditemukan. Jalankan `firebase login` dulu.');
  process.exit(1);
}

const toValue = (v) => {
  if (v === null || v === undefined) return { nullValue: null };
  if (typeof v === 'string') return { stringValue: v };
  if (typeof v === 'boolean') return { booleanValue: v };
  if (typeof v === 'number') return Number.isInteger(v) ? { integerValue: String(v) } : { doubleValue: v };
  if (v instanceof Date) return { timestampValue: v.toISOString() };
  if (typeof v === 'object' && 'seconds' in v) {
    return { timestampValue: new Date(v.seconds * 1000).toISOString() };
  }
  return null;
};

const fromValue = (v) => {
  if (!v || typeof v !== 'object') return undefined;
  if ('stringValue' in v) return v.stringValue;
  if ('booleanValue' in v) return v.booleanValue;
  if ('integerValue' in v) return Number(v.integerValue);
  if ('doubleValue' in v) return v.doubleValue;
  if ('timestampValue' in v) return v.timestampValue;
  if ('nullValue' in v) return null;
  return undefined;
};

const fieldsToObject = (fields = {}) =>
  Object.fromEntries(Object.entries(fields).map(([k, v]) => [k, fromValue(v)]));

async function listAll() {
  const out = [];
  let pageToken = '';
  do {
    const url = `${BASE}/transactions?pageSize=300${pageToken ? `&pageToken=${pageToken}` : ''}`;
    const res = await fetch(url, { headers: { Authorization: `Bearer ${accessToken}` } });
    if (!res.ok) throw new Error(`GET gagal ${res.status}: ${(await res.text()).slice(0, 200)}`);
    const json = await res.json();
    out.push(...(json.documents || []));
    pageToken = json.nextPageToken || '';
  } while (pageToken);
  return out;
}

async function patchDoc(doc, fields, updateTime) {
  const body = { fields: Object.fromEntries(Object.entries(fields).map(([k, v]) => [k, toValue(v)])) };
  const masks = Object.keys(fields).map((k) => `updateMask.fieldPaths=${encodeURIComponent(k)}`).join('&');
  const url = `https://firestore.googleapis.com/v1/${doc.name}?${masks}&currentDocument.updateTime=${encodeURIComponent(updateTime)}`;
  const res = await fetch(url, {
    method: 'PATCH',
    headers: { Authorization: `Bearer ${accessToken}`, 'Content-Type': 'application/json' },
    body: JSON.stringify(body)
  });
  if (!res.ok) throw new Error(`${doc.name.split('/').pop()} gagal ${res.status}: ${(await res.text()).slice(0, 200)}`);
  return res.json();
}

(async () => {
  console.log(`Mode: ${APPLY ? 'APPLY (menulis)' : 'DRY-RUN (tidak menulis)'}`);
  const docs = await listAll();
  console.log(`Dokumen transactions: ${docs.length}`);

  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  const backupDir = path.join(os.homedir(), 'Kontrack-backup', `tx-normalize-${stamp}`);
  const plan = [];
  const summary = new Map();

  for (const doc of docs) {
    const tx = fieldsToObject(doc.fields);
    const nextCategory = canonicalCategory(tx);
    const nextSource = canonicalSource(tx);

    const patch = {};
    if (nextCategory !== tx.category) patch.category = nextCategory;
    if (nextSource && nextSource !== tx.source) patch.source = nextSource;
    if (Object.keys(patch).length === 0) continue;

    const key = `${tx.category || '(kosong)'} -> ${patch.category || '(tetap)'}${patch.source ? ` [source: ${patch.source}]` : ''}`;
    summary.set(key, (summary.get(key) || 0) + 1);

    plan.push({
      id: doc.name.split('/').pop(),
      name: doc.name,
      updateTime: doc.updateTime,
      before: { category: tx.category, source: tx.source, type: tx.type, description: tx.description, amount: tx.amount },
      patch
    });
  }

  console.log(`\nPerlu diubah: ${plan.length} dari ${docs.length}`);
  for (const [k, v] of [...summary.entries()].sort((a, b) => b[1] - a[1])) {
    console.log(String(v).padStart(4), k);
  }

  if (plan.length === 0) {
    console.log('\nTidak ada yang perlu diubah. Selesai.');
    return;
  }

  fs.mkdirSync(backupDir, { recursive: true });
  fs.writeFileSync(path.join(backupDir, 'plan.json'), JSON.stringify(plan, null, 2));
  console.log(`\nRencana disimpan: ${path.join(backupDir, 'plan.json')}`);

  if (!APPLY) {
    console.log('\nJalankan ulang dengan --apply untuk menulis.');
    return;
  }

  let done = 0;
  const failed = [];
  for (const item of plan) {
    try {
      await patchDoc({ name: item.name }, item.patch, item.updateTime);
      done += 1;
    } catch (e) {
      failed.push({ id: item.id, error: e.message });
    }
  }

  fs.writeFileSync(path.join(backupDir, 'result.json'), JSON.stringify({ done, failed }, null, 2));
  console.log(`\nSelesai: ${done} diubah, ${failed.length} gagal.`);
  if (failed.length) {
    failed.slice(0, 5).forEach((f) => console.log('  gagal:', f.id, f.error));
  }
})();
