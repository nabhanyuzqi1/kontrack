// src/utils/transactionMeta.js
//
// Kanon kategori & sumber transaksi Kontrack.
//
// Sebelumnya tiga tempat menulis nama yang berbeda untuk hal yang SAMA di
// koleksi `transactions`, dan itu terlihat di data produksi (261 transaksi):
//
//   Pemasukan dari invoice : "Pembayaran"        (kode lama markInvoicePaid)
//                            "Pembayaran Invoice" (jalur live)
//                            "Pembayaran"          (input manual termin)
//   PPN atas invoice       : "Pengeluaran Lain"  (kode lama markInvoicePaid)
//                            "Pajak"              (jalur live)
//
// Akibatnya filter kategori, rekap, dan laporan proyek tidak pernah cocok
// antar-angkatan data. Berkas ini satu-satunya sumber kebenaran: kategori baru
// ditulis dari sini, dan data lama dinormalkan ke nilai yang sama.

// ---------------------------------------------------------------------------
// Kategori
// ---------------------------------------------------------------------------

export const INCOME_CATEGORIES = ['Proyek', 'Pembayaran Invoice', 'Lainnya'];

export const EXPENSE_CATEGORIES = [
  'Operasional',
  'Material',
  'Upah Karyawan/Tukang',
  'Pajak',
  'Pengeluaran Lain'
];

/**
 * Kategori kanonik untuk transaksi yang LAHIR dari siklus invoice (bukan input
 * manual pengguna). Dipakai `markInvoicePaid` dan normalisasi data lama.
 */
export const AUTO_CATEGORY = {
  // Uang masuk dari klien: netto yang benar-benar diterima.
  payment: 'Pembayaran Invoice',
  // PPN yang dipungut lalu disetor: beban pajak, bukan "pengeluaran lain".
  tax: 'Pajak'
};

/**
 * Penanda asal transaksi. Ini yang membedakan transaksi otomatis dari input
 * manual tanpa menebak dari deskripsi, dan membuat normalisasi bisa diulang
 * (idempoten) tanpa menyentuh entri yang diketik orang.
 */
export const TX_SOURCE = {
  invoicePayment: 'invoice',
  invoicePpn: 'invoice-ppn',
  invoiceTaxPayment: 'invoice-tax',
  manual: 'manual'
};

// ---------------------------------------------------------------------------
// Normalisasi nama kategori lama → kanonik
// ---------------------------------------------------------------------------

const INCOME_ALIASES = {
  pembayaran: 'Pembayaran Invoice',
  'pembayaran invoice': 'Pembayaran Invoice',
  proyek: 'Proyek',
  lainnya: 'Lainnya',
  lain: 'Lainnya'
};

const EXPENSE_ALIASES = {
  // PPN/PPh dari invoice dulu tercatat "Pengeluaran Lain" atau "Pajak".
  pajak: 'Pajak',
  'pengeluaran lain': 'Pengeluaran Lain',
  operasional: 'Operasional',
  material: 'Material',
  'upah karyawan/tukang': 'Upah Karyawan/Tukang',
  transportasi: 'Operasional'
};

const tidy = (s) => String(s ?? '').trim().replace(/\s+/g, ' ');

/**
 * Kembalikan kategori kanonik untuk sebuah transaksi.
 *
 * Aturan:
 * 1. Transaksi yang ditandai otomatis (`source` invoice*, atau
 *    `isAutoGenerated`) memakai AUTO_CATEGORY sesuai jenisnya. Ini yang
 *    membuat data lama "PPN Otomatis" → "Pajak" tanpa menebak dari deskripsi.
 * 2. Selain itu, nama lama dipetakan lewat alias tipe yang sesuai.
 * 3. Nama tak dikenal dibiarkan apa adanya: lebih baik kategori asing yang
 *    terlihat daripada nilai yang dikarang.
 *
 * @param {object} tx transaksi ({ type, category, source, isAutoGenerated })
 * @returns {string} kategori kanonik
 */
export const canonicalCategory = (tx = {}) => {
  const type = tx.type === 'expense' ? 'expense' : 'income';
  const source = String(tx.source || '');
  const auto = source.startsWith('invoice') || tx.isAutoGenerated === true;

  if (auto) {
    // "invoice-tax" adalah setoran PPN ke kas negara; "invoice-ppn" adalah
    // pengakuan beban PPN atas invoice. Keduanya pajak.
    if (source === TX_SOURCE.invoicePayment) return AUTO_CATEGORY.payment;
    if (source === TX_SOURCE.invoicePpn || source === TX_SOURCE.invoiceTaxPayment) return AUTO_CATEGORY.tax;
    if (type === 'income') return AUTO_CATEGORY.payment;

    // Pengeluaran otomatis TANPA `source` (angkatan kode lama): satu-satunya
    // pengeluaran otomatis yang pernah dibuat sistem adalah PPN invoice.
    // Sinyal lain (`invoiceId` terisi) dipakai sebagai bukti kedua, bukan
    // tebakan dari teks deskripsi yang bisa diubah pengguna.
    if (!source && tx.invoiceId) return AUTO_CATEGORY.tax;
  }

  const raw = tidy(tx.category);
  if (!raw) return type === 'expense' ? 'Pengeluaran Lain' : 'Lainnya';

  const table = type === 'expense' ? EXPENSE_ALIASES : INCOME_ALIASES;
  return table[raw.toLowerCase()] || raw;
};

/** Daftar kategori untuk dropdown, sudah bebas duplikat. */
export const categoriesFor = (type) =>
  type === 'expense' ? EXPENSE_CATEGORIES : INCOME_CATEGORIES;
